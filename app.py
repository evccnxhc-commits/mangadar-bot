# SEND MESSAGE TO FACEBOOK
# =========================================================

def send_message(recipient_id, message_text):

    if not PAGE_ACCESS_TOKEN:

        print("ERROR: PAGE_ACCESS_TOKEN is missing")

        return False

    url = "https://graph.facebook.com/v26.0/me/messages"

    params = {
        "access_token": PAGE_ACCESS_TOKEN
    }

    payload = {
        "recipient": {
            "id": recipient_id
        },
        "message": {
            "text": message_text
        }
    }

    try:

        response = requests.post(
            url,
            params=params,
            json=payload,
            timeout=30
        )

        print("Messenger status:", response.status_code)
        print("Messenger response:", response.text)

        if response.status_code == 200:
            print("Message sent successfully")
            return True

        print("Messenger send failed")

        return False

    except requests.exceptions.RequestException as e:

        print("Messenger request error:", str(e))

        return False

    except Exception as e:

        print("Messenger error:", str(e))

        return False


